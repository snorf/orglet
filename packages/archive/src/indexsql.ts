/**
 * The Heimdall index tables (csvfiles, objects, backup_runs) as documented in HEIMDALL-FORMAT section 3,
 * plus a deterministic INSERT renderer. Column types Heimdall does not document are orglet choices listed in
 * the fixture README. Re-derived from the documented shape; no Heimdall SQL is copied.
 */

export const INDEX_TABLES = ["csvfiles", "objects", "backup_runs"] as const;

/** Unqualified names so the caller's search_path picks the schema. */
export function indexDdl(): string {
  return `CREATE TABLE csvfiles (
  csv_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period integer NOT NULL,
  s3path text NOT NULL
);
CREATE TABLE objects (
  id text NOT NULL,
  period integer NOT NULL,
  version integer NOT NULL,
  metadata jsonb,
  org_id text NOT NULL,
  csv_id integer,
  is_deleted boolean DEFAULT false,
  object_name text,
  name text NOT NULL,
  PRIMARY KEY (org_id, period, id, version)
);
CREATE TABLE backup_runs (
  run_id bigserial PRIMARY KEY,
  object_name text,
  org_id text,
  period integer,
  status text,
  query_all boolean,
  started_at timestamp,
  completed_at timestamp,
  last_checkpoint_id text,
  last_checkpoint_modstamp timestamp,
  records_processed integer,
  records_failed integer,
  bytes_transferred bigint,
  error_message text,
  archive_expression text
);
`;
}

export interface CsvFileRow {
  csvId: number;
  period: number;
  s3path: string;
}

export interface ObjectRow {
  id: string;
  period: number;
  version: number;
  metadata: Record<string, string>;
  orgId: string;
  csvId: number;
  isDeleted: boolean;
  objectName: string;
  name: string;
}

export type BackupRunStatus = "Completed" | "Failed";

/** Timestamps are in Salesforce `+0000` form. */
export interface BackupRunRow {
  runId: number;
  objectName: string;
  orgId: string;
  period: number;
  status: BackupRunStatus;
  queryAll: boolean;
  startedAt: string;
  completedAt: string | null;
  lastCheckpointId: string | null;
  lastCheckpointModstamp: string | null;
  recordsProcessed: number | null;
  recordsFailed: number | null;
  bytesTransferred: number | null;
  errorMessage: string | null;
  archiveExpression: string | null;
}

export interface IndexRows {
  csvfiles: CsvFileRow[];
  objects: ObjectRow[];
  backupRuns: BackupRunRow[];
}

type Lit = string | number | boolean | null;

const str = (s: string): string => `'${s.replace(/'/g, "''")}'`;

function ts(sf: string): string {
  const m = /^(\d{4}-\d\d-\d\d)T(\d\d:\d\d:\d\d\.\d{3})\+0000$/.exec(sf);
  if (!m) throw new RangeError("timestamp: expected a Salesforce datetime ending in +0000");
  return `'${m[1]} ${m[2]}'`;
}

function lit(v: Lit): string {
  if (v === null) return "NULL";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return str(v);
}

const cmp = (a: string | number, b: string | number): number => (a < b ? -1 : a > b ? 1 : 0);

function insert(table: string, cols: string[], values: string[]): string {
  return `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${values.join(", ")});`;
}

/** Deterministic: tables in fixed order, rows by primary key, so shuffled input renders identical bytes. */
export function renderIndexSql(rows: IndexRows): string {
  const out: string[] = ["-- generated by `pnpm archive-fixture:gen`; do not edit", "", indexDdl()];

  const files = [...rows.csvfiles].sort((a, b) => a.csvId - b.csvId);
  for (const r of files) out.push(insert("csvfiles", ["csv_id", "period", "s3path"], [lit(r.csvId), lit(r.period), lit(r.s3path)]));

  const objects = [...rows.objects].sort(
    (a, b) => cmp(a.orgId, b.orgId) || a.period - b.period || cmp(a.id, b.id) || a.version - b.version,
  );
  const seen = new Set<string>();
  const objCols = ["id", "period", "version", "metadata", "org_id", "csv_id", "is_deleted", "object_name", "name"];
  for (const r of objects) {
    const key = JSON.stringify([r.orgId, r.period, r.id, r.version]);
    if (seen.has(key)) throw new Error("index: duplicate objects primary key");
    seen.add(key);
    out.push(
      insert(
        "objects",
        objCols,
        [lit(r.id), lit(r.period), lit(r.version), `${str(JSON.stringify(r.metadata))}::jsonb`, lit(r.orgId), lit(r.csvId), lit(r.isDeleted), lit(r.objectName), lit(r.name)],
      ),
    );
  }

  const runs = [...rows.backupRuns].sort((a, b) => a.runId - b.runId);
  const runCols = [
    "run_id", "object_name", "org_id", "period", "status", "query_all", "started_at", "completed_at", "last_checkpoint_id",
    "last_checkpoint_modstamp", "records_processed", "records_failed", "bytes_transferred", "error_message", "archive_expression",
  ];
  const tsOrNull = (v: string | null): string => (v === null ? "NULL" : ts(v));
  for (const r of runs) {
    out.push(
      insert("backup_runs", runCols, [
        lit(r.runId), lit(r.objectName), lit(r.orgId), lit(r.period), lit(r.status), lit(r.queryAll), ts(r.startedAt), tsOrNull(r.completedAt),
        lit(r.lastCheckpointId), tsOrNull(r.lastCheckpointModstamp), lit(r.recordsProcessed), lit(r.recordsFailed), lit(r.bytesTransferred),
        lit(r.errorMessage), lit(r.archiveExpression),
      ]),
    );
  }

  const maxCsv = files.reduce((m, r) => Math.max(m, r.csvId), 0);
  const maxRun = runs.reduce((m, r) => Math.max(m, r.runId), 0);
  out.push(`ALTER TABLE csvfiles ALTER COLUMN csv_id RESTART WITH ${maxCsv + 1};`);
  out.push(`ALTER SEQUENCE backup_runs_run_id_seq RESTART WITH ${maxRun + 1};`);
  return out.join("\n") + "\n";
}
