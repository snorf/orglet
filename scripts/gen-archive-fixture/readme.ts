/**
 * Generates examples/acme-archive/README.md, the contract for Phase 17/18/20/21 consumers (D-11); generated so `--check` covers it.
 */
export interface ReadmeFacts {
  orgId: string;
  periods: { segment: string; index: number; runAt: string; csvCount: number; objectRows: number }[];
  blobCount: number;
  failedObjects: string[];
  splitObject: string;
  splitLimit: number;
}

export function renderReadme(f: ReadmeFacts): string {
  const periodRows = f.periods.map((p, i) => `| ${i + 1} | \`Period=${p.segment}\` | ${p.index} | ${p.runAt} | ${p.csvCount} | ${p.objectRows} |`);
  const failed = f.failedObjects.length > 0 ? f.failedObjects.map((o) => `\`${o}\``).join(", ") : "(none)";
  return `${[
    "# acme-archive",
    "",
    "A generated, synthetic (Level 1) backup of `examples/acme` in the documented Heimdall backup layout, produced from orglet's own Bulk 2.0 query output. Heimdall is a separate open-source project; no Heimdall code or SQL is used here.",
    "",
    "## Layout",
    "",
    "- `store/` mirrors the bucket root.",
    `- CSV key: \`store/OrgId=${f.orgId}/Period=<yyyyMM>/Year=<yyyy>/Month=<MM>/Date=<dd>/<Object>[_deleted]/<750Id>.csv\``,
    `- Blob key: \`store/OrgId=${f.orgId}/Period=0/files/<checksum[0:4]>/<checksum>.<ext>\` (${f.blobCount} distinct blobs).`,
    "- `index.sql` holds the `csvfiles`, `objects` and `backup_runs` tables.",
    "- `csvfiles.s3path` is the bare key; resolve it under `store/`.",
    "",
    "## Periods",
    "",
    "| # | Key segment | Index `period` | Run at | CSV files | Object rows |",
    "| - | ----------- | -------------- | ------ | --------- | ----------- |",
    ...periodRows,
    "",
    "The key segment is `yyyyMM`; the index stores `YYMM` as an integer.",
    "",
    "- Period 1 is a full snapshot.",
    "- Period 2 is an increment: an account is renamed, a contact email changes, an opportunity is closed, project notes are rewritten, a milestone is reordered, an upsert row is renamed, and nine BigTable__c rows are touched.",
    "- Contact, Opportunity and UpsertTable__c each lose one record to `_deleted`.",
    "- Document \"Onboarding notes\" gets version 2.",
    "- \"Price list\" and \"Price list copy\" share one blob.",
    "- \"Logo\" is a non-UTF-8 binary.",
    "",
    "## Decisions where the Heimdall documentation is silent",
    "",
    "- `backup_runs.status` uses the values `Completed` and `Failed`.",
    "- The column types of `backup_runs` are orglet's choice.",
    "- `csv_id` is `GENERATED BY DEFAULT AS IDENTITY`; the dump restarts the identity and the run_id sequence after the last row.",
    "- `Month=` and `Date=` are two digits.",
    "- CSV file names are synthetic `750...` Ids; follow `csvfiles.s3path`, not the name.",
    `- \`${f.splitObject}\` uses LIMIT ${f.splitLimit} so it splits into two CSVs per period (real Heimdall uses 50K-200K).`,
    "- The deleted phase starts without a checkpoint.",
    "- Period 2 starts from period 1's last `(SystemModstamp, Id)` per object.",
    `- ${failed} is refused like a real org refuses an unfiltered query and gets a \`Failed\` run without a CSV; the loader must tolerate that.`,
    "- `objects.name` takes the first of Name/Subject/Title/CaseNumber/DeveloperName/Label that is present and non-empty, else Id.",
    "- `objects.metadata` includes `Id` itself.",
    "- A describe field named exactly `Tier` would be excluded.",
    "- Every blob has a non-empty extension (the empty-extension key is unverified).",
    "- `Period=0/files/` is shared by all periods.",
    "- `last_checkpoint_*` columns are informational.",
    "- Timestamps in `backup_runs` are UTC in `timestamp` columns.",
    "",
    "## Loading the index",
    "",
    "`psql -v ON_ERROR_STOP=1 -f index.sql` into an empty schema (set `search_path` first), or pglite `db.exec(text)`.",
    "",
    "## Regenerating",
    "",
    "Node 22, `pnpm archive-fixture:gen`, then commit. `pnpm archive-fixture:check` exits 1 on drift.",
  ].join("\n")}\n`;
}
